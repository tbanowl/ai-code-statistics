-- apscheduler_jobs (任务调度状态表)
CREATE TABLE IF NOT EXISTS apscheduler_jobs (
    -- 任务唯一标识（对应 job_id）
    id VARCHAR(191) NOT NULL,
    -- 下次运行时间（SQLite 使用 REAL 类型存储时间戳）
    next_run_time REAL,
    -- 任务序列化状态（包含 trigger, func, args 等）
    job_state BLOB NOT NULL,
    -- 主键约束
    PRIMARY KEY (id)
);

